#!/usr/bin/env node
/*
 * PocketWeb protocol golden-vector generator (JS reference).
 *
 * Emits the JS-side encoding results that the native Java PocketProtocol must
 * reproduce byte-for-byte. The two tricky, port-breaking operations are:
 *   1. encodetext(JSON.stringify(data))  -> the signature pre-image string
 *   2. JS JSON.stringify key ordering / escaping
 * Both are pure JS here (no node/MDS needed), so this is an independent oracle.
 *
 * Mirrors pocketFS/js/auth.js encodetext() exactly:
 *   encodeURIComponent(str).split("'").join("%27")
 *
 * Output: golden/vectors.json  (loaded by the Java test)
 */
const fs = require('fs');
const path = require('path');

function encodetext(str){
  return encodeURIComponent(str).split("'").join("%27");
}
// UTF-8 bytes of a string -> "0x" + UPPERCASE hex (mirrors `convert from:string to:hex`)
function strToHex0x(str){
  return "0x" + Buffer.from(str, 'utf8').toString('hex').toUpperCase();
}

// Build a filepacket .data object in the EXACT insertion order auth.js uses:
// name, owner, randid, description, version, file
function mkData(name, owner, randid, description, version, file){
  const d = {};
  d.name = name; d.owner = owner; d.randid = randid;
  d.description = description; d.version = version; d.file = file;
  return d;
}

// representative packets, including nasty description characters
const cases = [
  mkData(
    "Mx200GZ47HZKRAZKC99PZQVKUD4ER2G78NN6BT",
    "0x30819F300D06092A864886F70D010101050003818D00", // representative pubkey head
    "0x8A1F2C3D4E5F60718293A4B5C6D7E8F9",
    "no description yet..", 1, "0xDEADBEEF"),
  mkData("MxNAME","0xOWNER","0xRAND",
    "quotes ' \" and backslash \\ and slash / end", 2, "0xAABB"),
  mkData("MxNAME","0xOWNER","0xRAND",
    "unicode: café — 日本語 😀 \t tab \n newline", 7, "0xCAFE"),
  mkData("MxNAME","0xOWNER","0xRAND",
    "reserved !~*()-_. and space + & = # ? % []{}", 123, "0x00"),
  mkData("MxNAME","0xOWNER","0xRAND","", 0, "0x"),
];

const out = { note: "JS reference vectors for PocketProtocol parity", cases: [] };
for(const d of cases){
  const json = JSON.stringify(d);      // JS canonical, key order = insertion order
  const enc  = encodetext(json);       // signature pre-image string
  const hex  = strToHex0x(enc);        // what maxsign actually signs (data: hex)
  out.cases.push({
    data: d,
    json_stringify: json,
    encodetext: enc,
    preimage_hex: hex
  });
}

// also emit encodeURIComponent unit cases (char-level)
out.encodetext_units = {};
for(const s of ["a-z","A~Z","0.9","it's","a b","é","😀","/\\?#[]","*()!_-.~"]){
  out.encodetext_units[s] = encodetext(s);
}

const dir = path.join(__dirname, '..', 'app', 'src', 'test', 'resources', 'golden');
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'vectors.json'), JSON.stringify(out, null, 2));

// --- also emit a dependency-free Java source with the vectors as escaped literals ---
function jlit(s){
  let r = '"';
  for(const ch of s){
    const c = ch.codePointAt(0);
    if(ch === '"') r += '\\"';
    else if(ch === '\\') r += '\\\\';
    else if(ch === '\n') r += '\\n';
    else if(ch === '\r') r += '\\r';
    else if(ch === '\t') r += '\\t';
    else if(c < 0x20) r += '\\u' + c.toString(16).padStart(4,'0');
    else if(c > 0xFFFF){ // astral -> surrogate pair as \u\u
      const h = c - 0x10000;
      const hi = 0xD800 + (h >> 10), lo = 0xDC00 + (h & 0x3FF);
      r += '\\u'+hi.toString(16).padStart(4,'0')+'\\u'+lo.toString(16).padStart(4,'0');
    }
    else if(c > 0x7E) r += '\\u'+c.toString(16).padStart(4,'0'); // keep source ASCII
    else r += ch;
  }
  return r + '"';
}
let j = 'package com.eurobuddha.pocketweb;\n\n';
j += '/** AUTO-GENERATED by protocol-vectors/gen-vectors.js — do not edit. */\n';
j += 'public final class GoldenData {\n';
j += '  public static final class C { public final String name,owner,randid,description,file,json,enc,preimageHex; public final int version;\n';
j += '    C(String n,String o,String r,String d,int v,String f,String j,String e,String p){name=n;owner=o;randid=r;description=d;version=v;file=f;this.json=j;enc=e;preimageHex=p;} }\n';
j += '  public static final C[] CASES = new C[]{\n';
for(const c of out.cases){
  j += '    new C('+jlit(c.data.name)+','+jlit(c.data.owner)+','+jlit(c.data.randid)+','+
       jlit(c.data.description)+','+c.data.version+','+jlit(c.data.file)+','+
       jlit(c.json_stringify)+','+jlit(c.encodetext)+','+jlit(c.preimage_hex)+'),\n';
}
j += '  };\n';
j += '  public static final String[][] ENCODE_UNITS = new String[][]{\n';
for(const [k,v] of Object.entries(out.encodetext_units)){
  j += '    {'+jlit(k)+','+jlit(v)+'},\n';
}
j += '  };\n}\n';
const jdir = path.join(__dirname, '..', 'app', 'src', 'test', 'java', 'com', 'eurobuddha', 'pocketweb');
fs.mkdirSync(jdir, { recursive: true });
fs.writeFileSync(path.join(jdir, 'GoldenData.java'), j);

console.log("wrote", path.join(dir, 'vectors.json'), "and GoldenData.java with", out.cases.length,
  "packet cases +", Object.keys(out.encodetext_units).length, "unit cases");
